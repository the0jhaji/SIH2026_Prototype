"""Local training export for the Astra AI object-detection dataset (Phase 4C).

Turns the session-aware annotated split (built by ``prepare_split.py``) into a
YOLO ``data.yaml`` the ultralytics trainer consumes, and installs a trained
ONNX export into ``models/detection/`` with the matching ``.names`` file the
runtime detector understands.

Pure, camera-free logic (like ``dataset_tool.py`` / ``activity_tool.py``): no
training library is imported here; ultralytics runs on a machine of your
choosing (see ``dataset/requirements-train.txt``). Everything stays local —
weights only reach ``models/detection/`` through an explicit script run.
"""

from __future__ import annotations

import shutil
from pathlib import Path

from annotation.annotator import SPLITS, load_classes, validate_dataset

TRAINING_DIR_NAME = "training"
DATA_YAML_NAME = "data.yaml"


def make_data_yaml(
    split_root: Path,
    classes: list[str] | None = None,
    output: Path | None = None,
) -> dict:
    """Validate the split and write ``data.yaml`` for ultralytics training.

    Fails loudly on anything that would poison training: missing label files
    (blank labels are fine), out-of-range class ids, malformed boxes, and
    cross-split session leakage. Train and val must both have images; test is
    optional.

    The YAML is location-independent: ``path`` is the absolute split root and
    ``train/val/test`` point at the ``*/images`` dirs, so the trainer resolves
    them wherever the dataset lives.
    """
    split_root = Path(split_root).resolve()
    if classes is None:
        classes = load_classes()
    report = validate_dataset(split_root, classes=classes)
    if report.errors:
        # A warning-style preview keeps the message readable for big datasets.
        raise ValueError(
            f"split is not trainable ({len(report.errors)} problem(s)):\n"
            + "\n".join(report.errors[:15])
            + (f"\n… and {len(report.errors) - 15} more" if len(report.errors) > 15 else "")
        )
    for required in ("train", "val"):
        info = report.stats.get(required)
        if not info or not info.get("images"):
            raise ValueError(f"split has no '{required}' images under {split_root}")

    yaml_path = Path(output) if output is not None else split_root / TRAINING_DIR_NAME / DATA_YAML_NAME
    yaml_path = yaml_path.resolve()
    if yaml_path.name != DATA_YAML_NAME:
        yaml_path = yaml_path / DATA_YAML_NAME
    yaml_path.parent.mkdir(parents=True, exist_ok=True)

    names_block = "".join(f"  {i}: {name}\n" for i, name in enumerate(classes))
    optional_test = "test: test/images\n" if report.stats.get("test", {}).get("images") else ""
    body = (
        "# Astra AI object-detection dataset - generated by dataset/training_tool.py\n"
        f"path: {split_root.as_posix()}\n"
        "train: train/images\n"
        "val: val/images\n"
        + optional_test
        + f"nc: {len(classes)}\n"
        f"names:\n{names_block}"
    )
    yaml_path.write_text(body, encoding="utf-8")

    return {
        "yaml": str(yaml_path),
        "classes": list(classes),
        "images": {
            split: report.stats[split]["images"] for split in SPLITS if split in report.stats
        },
        "histogram": class_histogram(split_root, len(classes)),
    }


def class_histogram(split_root: Path, n_classes: int) -> dict[str, list[int]]:
    """Per-split count of boxes per class id (reads the split label files)."""
    split_root = Path(split_root)
    hist: dict[str, list[int]] = {}
    for split in SPLITS:
        counts = [0] * max(n_classes, 0)
        labels_dir = split_root / split / "labels"
        if labels_dir.is_dir():
            for label in labels_dir.rglob("*.txt"):
                for line in label.read_text(encoding="utf-8").splitlines():
                    line = line.strip()
                    if not line:
                        continue
                    try:
                        cls = int(line.split()[0])
                    except (ValueError, IndexError):
                        continue
                    if 0 <= cls < len(counts):
                        counts[cls] += 1
        hist[split] = counts
    return hist


def install_detection_model(
    onnx_path: Path,
    dest_dir: Path,
    classes: list[str] | None = None,
    dest_name: str = "yolov8n.onnx",
) -> dict:
    """Copy a trained ONNX export into ``dest_dir`` for the runtime detector.

    Writes the matching ``.names`` file (one class per line, index-aligned
    with the trained model) next to the weights, which is how
    ``ai/detection/yolo_detector.py`` learns the real class list. Classes
    default to ``annotation/classes.json`` so the installed model always
    matches the dataset it was trained on.
    """
    src = Path(onnx_path).expanduser().resolve()
    if not src.is_file():
        raise FileNotFoundError(f"ONNX model not found: {src}")
    if classes is None:
        classes = load_classes()
    dest_dir = Path(dest_dir).expanduser().resolve()
    dest_dir.mkdir(parents=True, exist_ok=True)
    onnx_dest = dest_dir / dest_name
    shutil.copy2(src, onnx_dest)
    names_dest = onnx_dest.with_suffix(".names")
    names_dest.write_text("\n".join(str(name) for name in classes) + "\n", encoding="utf-8")
    return {
        "onnx": str(onnx_dest),
        "names": str(names_dest),
        "classes": list(classes),
    }