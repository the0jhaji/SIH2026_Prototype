"""Visual annotation tool: proposals in, human-verified labels out.

    .\\.venv\\Scripts\\python.exe experiment\\yolo_training\\annotate.py
    .\\.venv\\Scripts\\python.exe experiment\\yolo_training\\annotate.py --port 8002 --reindex
    .\\.venv\\Scripts\\python.exe experiment\\yolo_training\\annotate.py --session session_20260830_004243_wr66

Open the printed URL. Draw, resize, move, delete and reclassify boxes; the
proposals generated by ``prelabel.py`` are shown dashed so it is obvious they are
candidates, not answers. Save with the button or ``S``.

The one rule this tool enforces: a frame only becomes a training row once
``reviewed`` is set, and that is a human pressing save (section 6). Nothing in
this file creates a label on its own.
"""

from __future__ import annotations

import argparse
import json
import sys
from contextlib import asynccontextmanager
from pathlib import Path
from typing import Optional

from fastapi import FastAPI, HTTPException
from fastapi.responses import FileResponse, HTMLResponse
from pydantic import BaseModel, Field

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[1]
for p in (str(REPO_ROOT), str(HERE)):
    if p not in sys.path:
        sys.path.insert(0, p)

import experiment_tool as et  # noqa: E402

#: Display colours per class id. Distinct hues only; the number keys are what
#: the annotator actually relies on.
CLASS_COLORS = [
    (90, 200, 255),  # person
    (255, 180, 90),  # main_experiment_box
    (60, 70, 245),  # red_box
    (60, 220, 235),  # yellow_box
    (140, 90, 240),  # red_target_area
    (90, 150, 245),  # yellow_target_area
]

def _load_index() -> None:
    global INDEX
    et.ensure_layout()
    try:
        INDEX = et.load_index()
    except FileNotFoundError:
        INDEX = et.build_index()
        et.save_index(INDEX)


@asynccontextmanager
async def lifespan(_: FastAPI):
    _load_index()
    yield


app = FastAPI(title="ASTRA experiment annotation", docs_url=None, redoc_url=None, lifespan=lifespan)

INDEX: dict = {}


def _session_meta(session_id: str) -> dict:
    for session in INDEX.get("sessions", []):
        if session["session_id"] == session_id:
            return session
    raise HTTPException(404, f"unknown session {session_id}")


def _frame(session_id: str, frame_id: int) -> dict:
    session = _session_meta(session_id)
    for frame in session.get("frames", []):
        if int(frame["frame_id"]) == int(frame_id):
            return frame
    raise HTTPException(404, f"unknown frame {frame_id} in {session_id}")


def _image_size(session_id: str) -> tuple[int, int]:
    """Camera size from the session's own metadata, so normalization matches
    the pixels that were actually recorded."""
    for rel in (f"dataset/raw/*/{session_id}", f"dataset/activity/*/{session_id}"):
        for meta in REPO_ROOT.glob(f"{rel}/metadata.json"):
            camera = json.loads(meta.read_text(encoding="utf-8")).get("camera", {})
            if camera.get("width") and camera.get("height"):
                return int(camera["width"]), int(camera["height"])
    return 1280, 720


class Box(BaseModel):
    class_: str = Field(alias="class")
    bbox: list[float] = Field(min_length=4, max_length=4)
    source: str = "manual"

    model_config = {"populate_by_name": True}


class SaveRequest(BaseModel):
    session_id: str
    frame_id: int
    boxes: list[Box]
    reviewed: bool = True
    image_size: Optional[list[int]] = None


class ReviewRequest(BaseModel):
    session_id: str
    frame_id: int
    reviewed: bool


@app.get("/", response_class=HTMLResponse)
def index_page() -> str:
    return (HERE / "annotate.html").read_text(encoding="utf-8")


@app.get("/api/config")
def config() -> dict:
    vocab = et.load_vocabulary()
    return {
        "classes": [
            {
                "id": i,
                "name": name,
                "color": list(CLASS_COLORS[i % len(CLASS_COLORS)]),
                "proposable": name in et.PROPOSABLE,
                "note": vocab.notes.get(name, ""),
            }
            for i, name in enumerate(vocab.classes)
        ],
        "keys": {"next": "N", "prev": "P", "delete": "D", "save": "S"},
    }


@app.get("/api/sessions")
def sessions() -> dict:
    rows = []
    for session in INDEX.get("sessions", []):
        sid = session["session_id"]
        sampling = et.SAMPLING_DIR / f"{sid}.json"
        sampled = set()
        if sampling.is_file():
            sampled = {int(x) for x in json.loads(sampling.read_text(encoding="utf-8"))["frame_ids"]}
        # progress comes from the shared state function, never a second tally
        states = [et.annotation_state(sid, f["frame_id"]) for f in session.get("frames", [])]
        reviewed = sum(1 for s in states if s["reviewed"])
        rows.append(
            {
                "session_id": sid,
                "label": session.get("label"),
                "activity": session.get("activity"),
                "n_frames": session.get("n_frames", 0),
                "n_sampled": len(sampled),
                "n_reviewed": reviewed,
                "n_annotated": sum(1 for s in states if s["has_metadata"]),
                "n_remaining": (len(sampled) - reviewed) if sampled else 0,
                "frame_ids": [int(f["frame_id"]) for f in session.get("frames", [])],
            }
        )
    return {"sessions": rows, "totals": INDEX.get("totals", {})}


@app.get("/api/frame/{session_id}/{frame_id}")
def frame_detail(session_id: str, frame_id: int) -> dict:
    frame = _frame(session_id, frame_id)
    state = et.annotation_state(session_id, frame_id)
    width, height = state["image_size"] if any(state["image_size"]) else _image_size(session_id)
    return {
        "session_id": session_id,
        "frame_id": frame_id,
        "key": state["key"],
        "filename": frame["filename"],
        "activity": frame.get("activity"),
        "image_url": f"/api/image/{session_id}/{frame_id}",
        "image_size": [width, height],
        "proposals": et.load_proposals(session_id, frame_id),
        "annotations": state["annotations"],
        "reviewed": state["reviewed"],
        "empty": state["empty"],
    }


@app.get("/api/image/{session_id}/{frame_id}")
def frame_image(session_id: str, frame_id: int) -> FileResponse:
    frame = _frame(session_id, frame_id)
    path = REPO_ROOT / frame["source"]
    if not path.is_file():
        raise HTTPException(404, f"missing {path}")
    return FileResponse(path, media_type="image/jpeg")


@app.get("/api/next/{session_id}")
def next_frame(session_id: str, after: int = -1) -> dict:
    """Next frame a human still has to judge: sampled, not yet reviewed."""
    sampling = et.SAMPLING_DIR / f"{session_id}.json"
    ids = (
        [int(x) for x in json.loads(sampling.read_text(encoding="utf-8"))["frame_ids"]]
        if sampling.is_file()
        else [int(f["frame_id"]) for f in _session_meta(session_id).get("frames", [])]
    )
    ids = sorted(ids)
    remaining = [f for f in ids if not et.annotation_state(session_id, f)["reviewed"]]
    for fid in ids:
        if fid > after and fid in remaining:
            return {"frame_id": fid, "reviewed": 0, "remaining": len(remaining)}
    return {"frame_id": ids[-1] if ids else 0, "reviewed": 1, "remaining": 0}


@app.post("/api/save")
def save(payload: SaveRequest) -> dict:
    frame = _frame(payload.session_id, payload.frame_id)
    width, height = (payload.image_size or _image_size(payload.session_id))
    boxes = [{"class": b.class_, "bbox": b.bbox} for b in payload.boxes]
    entry = et.save_annotations(
        payload.session_id,
        payload.frame_id,
        boxes,
        source=frame["source"],
        activity=frame.get("activity"),
        reviewed=payload.reviewed,
        image_size=(width, height),
    )
    # Confirm what was actually stored. A silent "saved" for an unreviewed
    # frame is what made a whole session of real labels look unfinalized.
    stored = et.annotation_state(payload.session_id, payload.frame_id)
    nxt = next_frame(payload.session_id, payload.frame_id)
    return {
        "ok": True,
        "frame": entry,
        "reviewed": stored["reviewed"],
        "key": stored["key"],
        "n_boxes": stored["n_boxes"],
        "next": nxt,
        "empty": stored["empty"],
    }


@app.post("/api/review")
def review(payload: ReviewRequest) -> dict:
    """Record the review decision for one frame, independently of its boxes.

    This is the fix for the lost flag: ticking the box persists immediately, so
    it survives navigation, a refresh, and labels written by an older tool
    version that must not be redrawn.
    """
    _frame(payload.session_id, payload.frame_id)
    state = et.set_reviewed(payload.session_id, payload.frame_id, payload.reviewed)
    return {"ok": True, "reviewed": state["reviewed"], "key": state["key"],
            "n_boxes": state["n_boxes"]}


@app.get("/api/stats")
def stats() -> dict:
    report = et.dataset_report(INDEX)
    return report


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--host", default="127.0.0.1")
    ap.add_argument("--port", type=int, default=8002)
    ap.add_argument("--reindex", action="store_true", help="rebuild index.json on start")
    ap.add_argument("--session", default=None, help="jump straight to this session")
    args = ap.parse_args(argv)

    import uvicorn

    global INDEX
    et.ensure_layout()
    INDEX = et.build_index() if args.reindex or not et.INDEX_FILE.is_file() else et.load_index()
    et.save_index(INDEX)
    print(f"index: {INDEX['totals']}")
    print(f"open http://{args.host}:{args.port}/" + (f"?session={args.session}" if args.session else ""))
    print("reminder: proposals are candidates. Only a human save makes a label.")
    uvicorn.run(app, host=args.host, port=args.port, log_level="warning")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
